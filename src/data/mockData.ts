// Helper to generate a 2+2 seat matrix (Rows 1 to 9, columns A, B, aisle, C, D)
export const generateSeatLayout = (trip: BusTrip) => {
  const rows = 9; // 9 rows x 4 seats = 36 total seats in standard 2+2 layout
  const seats = [];

  for (let r = 1; r <= rows; r++) {
    const cols: Array<'A' | 'B' | 'C' | 'D'> = ['A', 'B', 'C', 'D'];
    for (const c of cols) {
      const seatId = `${r}${c}`;
      const isOccupied = trip.occupiedSeatIds.includes(seatId);
      const isFront = r === 1;
      
      // VIP front row or standard
      const seatPrice = isFront ? trip.price + 50 : trip.price;
      const type = isFront ? ('front' as const) : ('standard' as const);

      seats.push({
        id: seatId,
        row: r,
        column: c,
        label: seatId,
        type,
        price: seatPrice,
        isOccupied,
        isSelected: false,
      });
    }
  }

  return seats;
};
